-- 1. جدول الملفات الشخصية (profiles)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name TEXT,
  first_name TEXT,
  father_name TEXT,
  family_name TEXT,
  username TEXT UNIQUE,
  avatar_url TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- تفعيل RLS على profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "المستخدمون يمكنهم قراءة ملفاتهم الشخصية"
  ON public.profiles FOR SELECT
  TO authenticated
  USING (auth.uid() = id);

CREATE POLICY "المستخدمون يمكنهم تعديل ملفاتهم الشخصية"
  ON public.profiles FOR UPDATE
  TO authenticated
  USING (auth.uid() = id);

CREATE POLICY "المستخدمون يمكنهم إنشاء ملفاتهم الشخصية"
  ON public.profiles FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = id);

-- 2. دالة وتريجر لإنشاء الملف الشخصي تلقائياً عند تسجيل مستخدم جديد
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
  raw_meta JSONB := NEW.raw_user_meta_data;
  f_name TEXT := raw_meta->>'first_name';
  fat_name TEXT := raw_meta->>'father_name';
  fam_name TEXT := raw_meta->>'family_name';
  d_name TEXT := raw_meta->>'display_name';
  u_name TEXT := raw_meta->>'username';
BEGIN
  IF d_name IS NULL OR d_name = '' THEN
    d_name := TRIM(CONCAT(COALESCE(f_name, ''), ' ', COALESCE(fat_name, ''), ' ', COALESCE(fam_name, '')));
    IF d_name = '' THEN
      d_name := COALESCE(NEW.email, 'مستخدم جديد');
    END IF;
  END IF;

  INSERT INTO public.profiles (id, display_name, first_name, father_name, family_name, username)
  VALUES (NEW.id, d_name, f_name, fat_name, fam_name, u_name)
  ON CONFLICT (id) DO UPDATE SET
    display_name = EXCLUDED.display_name,
    first_name = EXCLUDED.first_name,
    father_name = EXCLUDED.father_name,
    family_name = EXCLUDED.family_name,
    username = COALESCE(EXCLUDED.username, public.profiles.username),
    updated_at = now();

  -- تهيئة إحصائيات أولية للمستخدم
  INSERT INTO public.quran_user_stats (user_id, total_verses_memorized, total_pages, current_streak, longest_streak, daily_average)
  VALUES (NEW.id, 0, 0, 0, 0, 0)
  ON CONFLICT (user_id) DO NOTHING;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 3. جدول تقدم السور (quran_progress)
CREATE TABLE IF NOT EXISTS public.quran_progress (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  surah_id INTEGER NOT NULL CHECK (surah_id >= 1 AND surah_id <= 114),
  verses_memorized INTEGER NOT NULL DEFAULT 0,
  strength INTEGER NOT NULL DEFAULT 0 CHECK (strength >= 0 AND strength <= 100),
  status TEXT NOT NULL DEFAULT 'not_started' CHECK (status IN ('not_started', 'in_progress', 'memorized', 'needs_review')),
  memorized_at TIMESTAMPTZ,
  last_review TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  CONSTRAINT unique_user_surah UNIQUE (user_id, surah_id)
);

ALTER TABLE public.quran_progress ENABLE ROW LEVEL SECURITY;

CREATE POLICY "المستخدم يتحكم في تقدم سوره الخاصة"
  ON public.quran_progress FOR ALL
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS idx_quran_progress_user ON public.quran_progress(user_id);
CREATE INDEX IF NOT EXISTS idx_quran_progress_user_surah ON public.quran_progress(user_id, surah_id);

-- 4. جدول الأهداف اليومية (quran_daily_goals)
CREATE TABLE IF NOT EXISTS public.quran_daily_goals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  goal_date DATE NOT NULL,
  target_verses INTEGER NOT NULL DEFAULT 52,
  completed_verses INTEGER NOT NULL DEFAULT 0,
  target_review INTEGER NOT NULL DEFAULT 20,
  completed_review INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  CONSTRAINT unique_user_goal_date UNIQUE (user_id, goal_date)
);

ALTER TABLE public.quran_daily_goals ENABLE ROW LEVEL SECURITY;

CREATE POLICY "المستخدم يتحكم في أهدافه اليومية"
  ON public.quran_daily_goals FOR ALL
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS idx_quran_daily_goals_user_date ON public.quran_daily_goals(user_id, goal_date);

-- 5. جدول إحصائيات المستخدم (quran_user_stats)
CREATE TABLE IF NOT EXISTS public.quran_user_stats (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  total_verses_memorized INTEGER NOT NULL DEFAULT 0,
  total_pages INTEGER NOT NULL DEFAULT 0,
  current_streak INTEGER NOT NULL DEFAULT 0,
  longest_streak INTEGER NOT NULL DEFAULT 0,
  start_date TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  target_end_date TIMESTAMPTZ,
  daily_average NUMERIC(6, 2) DEFAULT 0,
  weekly_progress JSONB DEFAULT '[0, 0, 0, 0, 0, 0, 0]'::jsonb,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.quran_user_stats ENABLE ROW LEVEL SECURITY;

CREATE POLICY "المستخدم يتحكم في إحصائياته"
  ON public.quran_user_stats FOR ALL
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

-- 6. جدول سجل المراجعة والتسميع (quran_review_history)
CREATE TABLE IF NOT EXISTS public.quran_review_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  surah_id INTEGER NOT NULL CHECK (surah_id >= 1 AND surah_id <= 114),
  verses INTEGER NOT NULL DEFAULT 0,
  strength INTEGER NOT NULL DEFAULT 0,
  event_type TEXT NOT NULL DEFAULT 'review' CHECK (event_type IN ('memorization', 'review')),
  event_date TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.quran_review_history ENABLE ROW LEVEL SECURITY;

CREATE POLICY "المستخدم يتحكم في سجل مراجعاته"
  ON public.quran_review_history FOR ALL
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS idx_quran_review_history_user_date ON public.quran_review_history(user_id, event_date DESC);

